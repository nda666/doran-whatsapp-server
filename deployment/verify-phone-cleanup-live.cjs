const assert = require('node:assert/strict');
const { randomUUID, createHash } = require('node:crypto');
const fs = require('node:fs/promises');
const path = require('node:path');
require('@next/env').loadEnvConfig(process.cwd());
const { PrismaClient } = require('@prisma/client');
const db = new PrismaClient();
const origin = 'https://dashboard.jeblast.com';
const all = { disconnect: true, clearAuth: true, clearContacts: true, clearHistory: true, clearAutoReplies: true, resetToken: true, resetSettings: true, deleteRecord: false };
const empty = Object.fromEntries(Object.keys(all).map(key => [key, false]));
const fixtureIds = [], userIds = [], checks = [];
let owner, outsider, uiId;
const stamp = Date.now();
const label = `Codex Cleanup Live Test ${stamp}`;
const artifact = path.resolve('deployment/phone-cleanup-live-fixture.json');
const digest = rows => createHash('sha256').update(JSON.stringify(rows)).digest('hex');
function authFolder(id) {
  const root = path.resolve('./storage/whatsapp-auth');
  const target = path.resolve(root, `${owner.id}-${id}`);
  assert.equal(path.dirname(target), root); return target;
}
async function api(id, options, token = owner.token, method = 'POST') {
  const response = await fetch(`${origin}/api/phones/${id}`, { method, headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json' },
    ...(method === 'POST' ? { body: JSON.stringify(options) } : {}), signal: AbortSignal.timeout(45000) });
  const body = await response.json(); return { code: response.status, body };
}
async function tokenStatus(token) {
  return (await fetch(origin + '/api/session', { headers: { Authorization: 'Bearer ' + token }, signal: AbortSignal.timeout(10000) })).status;
}
async function getPhone(id) { return db.phone.findUniqueOrThrow({ where: { id } }); }
async function makePhone(name) {
  const phone = await db.phone.create({ data: { name, userId: owner.id, active: 0, webhookUrl: 'https://example.invalid/cleanup-test', rejectCall: true, showTyping: true } });
  fixtureIds.push(phone.id); return phone;
}
async function makeUser(suffix) {
  const user = await db.user.create({ data: { name: 'Codex disposable live test', email: `codex-cleanup-${stamp}-${suffix}@example.invalid`, password: randomUUID(), token: randomUUID(), role: 'USER', approvalStatus: 'APPROVED', isActive: true } });
  userIds.push(user.id); return user;
}
async function cleanFixtures(keepUI) {
  for (const id of fixtureIds) {
    if (keepUI && id === uiId) continue;
    // Fixture identifiers are generated by this script; never match real devices by name.
    try { await api(id, { ...all, deleteRecord: true }); } catch {}
    await db.waDispatch.deleteMany({ where: { phoneId: id, userId: owner.id } });
    await db.deviceContact.deleteMany({ where: { phoneId: id, userId: owner.id } });
    await db.waSenderLease.deleteMany({ where: { phoneId: id } });
    await db.phone.deleteMany({ where: { id, userId: owner.id } });
    await fs.rm(authFolder(id), { recursive: true, force: true });
  }
  for (const id of userIds) if (!keepUI || id !== owner.id) await db.user.deleteMany({ where: { id, email: { startsWith: `codex-cleanup-${stamp}-` } } });
}
(async () => {
  const original = await db.phone.findMany({ select: { id: true, token: true }, orderBy: { id: 'asc' } });
  let success = false;
  try {
    owner = await makeUser('owner'); outsider = await makeUser('outsider');
    const phone = await makePhone(label + ' API');
    assert.equal((await api(phone.id, all, outsider.token)).code, 404);
    assert.equal((await api(phone.id, empty)).code, 400);
    const anonymous = await fetch(`${origin}/api/phones/${phone.id}`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(all) });
    assert.equal(anonymous.status, 401);
    assert.equal((await getPhone(phone.id)).token, phone.token);
    checks.push('unauthorized/other owner/empty selection rejected');
    await db.waSenderLease.create({ data: { phoneId: phone.id, leaseToken: randomUUID(), leaseUntil: new Date(Date.now() + 60000) } });
    assert.equal((await api(phone.id, all)).code, 409);
    await db.waSenderLease.update({ where: { phoneId: phone.id }, data: { leaseToken: null, leaseUntil: null } });
    checks.push('busy sender rejected without resetting token');
    assert.equal((await api(phone.id, { ...empty, resetSettings: true })).code, 200);
    let current = await getPhone(phone.id);
    assert.equal(current.token, phone.token); assert.equal(current.webhookUrl, null);
    await db.phone.update({ where: { id: phone.id }, data: { webhookUrl: 'https://example.invalid/cleanup-test' } });
    assert.equal((await api(phone.id, { ...empty, resetToken: true })).code, 200);
    current = await getPhone(phone.id);
    assert.notEqual(current.token, phone.token); assert.equal(current.webhookUrl, 'https://example.invalid/cleanup-test');
    assert.equal(await tokenStatus(phone.token), 401); assert.equal(await tokenStatus(current.token), 200);
    checks.push('independent token rotation: old token 401/new token 200; settings-only keeps token');
    await db.deviceContact.create({ data: { userId: owner.id, phoneId: phone.id, number: '6280000000000', name: 'Disposable fixture' } });
    await db.autoReply.create({ data: { userId: owner.id, phoneId: phone.id, keyword: 'codex-disposable', reply: { text: 'fixture' } } });
    const job = await db.waDispatch.create({ data: { userId: owner.id, phoneId: phone.id, storeId: 'CODEX_TEST', transactionId: randomUUID(), messageKey: 'fixture', recipient: '6280000000000', dedupeKey: createHash('sha256').update(randomUUID()).digest('hex'), payloadHash: createHash('sha256').update('fixture').digest('hex'), message: 'Disposable fixture; do not send', status: 'FAILED', expiresAt: new Date() } });
    await db.dispatchWebhookEvent.create({ data: { eventId: randomUUID(), dispatchId: job.id, event: 'fixture', revision: randomUUID(), status: 'CANCELLED' } });
    await fs.mkdir(authFolder(phone.id), { recursive: true }); await fs.writeFile(path.join(authFolder(phone.id), 'disposable-fixture.txt'), 'test-only');
    const preservedToken = current.token;
    const reset = await api(phone.id, { ...all, resetToken: false });
    assert.equal(reset.code, 200, JSON.stringify(reset.body));
    current = await getPhone(phone.id);
    assert.equal(current.id, phone.id); assert.equal(current.name, phone.name); assert.equal(current.token, preservedToken);
    assert.equal(current.active, 1); assert.equal(current.status, 'CLOSE'); assert.equal(current.isOnline, false);
    assert.equal(current.number, null); assert.equal(current.account_name, null); assert.equal(current.webhookUrl, null);
    assert.equal(await db.deviceContact.count({ where: { phoneId: phone.id } }), 0);
    assert.equal(await db.autoReply.count({ where: { phoneId: phone.id } }), 0);
    assert.equal(await db.waDispatch.count({ where: { phoneId: phone.id } }), 0);
    assert.equal(await db.dispatchWebhookEvent.count({ where: { dispatchId: job.id } }), 0);
    await assert.rejects(fs.stat(authFolder(phone.id)), { code: 'ENOENT' });
    checks.push('full reset keeps device row/token when unchecked; clears contacts/replies/dispatches/webhook history/auth folder');
    const qr = await fetch(origin + '/api/generate-qr', { method: 'POST', headers: { Authorization: 'Bearer ' + current.token, 'Content-Type': 'application/json' }, body: '{}', signal: AbortSignal.timeout(30000) });
    const qrData = await qr.json(); assert.equal(qr.status, 200); assert.ok(qrData.qr, 'new QR must be available; never scan test QR');
    assert.equal((await api(phone.id, all)).code, 200);
    current = await getPhone(phone.id); assert.notEqual(current.token, preservedToken); assert.equal(current.isOnline, false);
    await assert.rejects(fs.stat(authFolder(phone.id)), { code: 'ENOENT' });
    const freshQR = await fetch(origin + '/api/generate-qr', { method: 'POST', headers: { Authorization: 'Bearer ' + current.token, 'Content-Type': 'application/json' }, body: '{}', signal: AbortSignal.timeout(30000) });
    const freshData = await freshQR.json(); assert.equal(freshQR.status, 200); assert.ok(freshData.qr); assert.notEqual(freshData.qr, qrData.qr);
    checks.push('live QR socket cleared and fresh QR generated after full reset');
    assert.equal((await api(phone.id, undefined, owner.token, 'DELETE')).code, 200);
    assert.equal(await db.phone.findUnique({ where: { id: phone.id } }), null);
    assert.equal(await tokenStatus(current.token), 401);
    await assert.rejects(fs.stat(authFolder(phone.id)), { code: 'ENOENT' });
    checks.push('delete removes test device/token/auth and closes QR socket');
    const ui = await makePhone(label + ' UI'); uiId = ui.id;
    await fs.writeFile(artifact, JSON.stringify({ phoneId: ui.id, userId: owner.id, label: ui.name, testUserIds: userIds, checks }, null, 2));
    const after = await db.phone.findMany({ where: { id: { in: original.map(row => row.id) } }, select: { id: true, token: true }, orderBy: { id: 'asc' } });
    assert.equal(digest(after), digest(original), 'existing devices and tokens must be preserved');
    checks.push('all existing device IDs and tokens preserved');
    success = true;
    console.log('PHONE_CLEANUP_LIVE_OK', JSON.stringify(checks));
    console.log('UI_FIXTURE', ui.name, ui.id);
  } finally { if (owner) await cleanFixtures(success); }
})().catch(error => { console.error('LIVE_TEST_FAILED', error.message); process.exitCode = 1; }).finally(() => db.$disconnect());
