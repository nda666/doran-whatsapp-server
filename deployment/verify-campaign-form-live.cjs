const assert = require('node:assert/strict');
const fs = require('node:fs');
require('@next/env').loadEnvConfig(process.cwd());
const { PrismaClient } = require('@prisma/client');
const p = new PrismaClient();
(async () => {
  const owner = await p.user.findFirst({ where: { role: 'ADMIN' } });
  assert(owner);
  const { encode } = require('next-auth/jwt');
  const jwt = await encode({ token: { id: owner.id, token: owner.token, name: owner.name, email: owner.email }, secret: process.env.NEXTAUTH_SECRET });
  const base = 'https://dashboard.jeblast.com';
  const response = await fetch(base + '/dashboard/campaigns', { redirect: 'manual', headers: { Cookie: '__Secure-next-auth.session-token=' + jwt } });
  assert.equal(response.status, 200);
  const html = await response.text();
  assert(html.includes('Isi pesan otomatis:'));
  assert(html.includes('pesan pertama memakai perangkat A'));
  assert(!html.includes('Personalisasi dengan {nama} dan {nomor}.'));
  const data = JSON.parse(html.match(/<script id="__NEXT_DATA__"[^>]*>([\s\S]*?)<\/script>/)[1]);
  assert.equal(data.buildId, fs.readFileSync('.next/BUILD_ID', 'utf8').trim());
  const chunk = html.match(/src="([^"]*\/pages\/dashboard\/campaigns-[^"]+\.js)"/);
  assert(chunk, 'Campaign chunk missing');
  const asset = await fetch(new URL(chunk[1], base));
  assert.equal(asset.status, 200);
  const js = await asset.text();
  for (const label of ['Input manual (satu baris: nomor|nama)', 'Pilih grup dari menu Kontak', 'Delay waktu pengiriman antar pesan', '10.000 karakter', 'Jika kontak tidak memiliki nama']) assert(js.includes(label), label);
  assert(!js.includes('Nomor manual (satu baris: nomor|nama)'));
  assert(!/[\uFFFD\u00C3\u00C2]/.test(js), 'Unexpected corrupted characters');
  const groups = await fetch(base + '/api/contacts/groups', { headers: { Authorization: 'Bearer ' + owner.token } });
  assert.equal(groups.status, 200);
  const rows = await groups.json();
  assert(Array.isArray(rows));
  assert(rows.every(g => typeof g.id === 'string' && typeof g.name === 'string' && typeof g._count.contacts === 'number'));
  console.log('CAMPAIGN_PUBLIC_HTML_JS_LABELS_UTF8_CONTACT_GROUPS_VERIFIED', data.buildId, 'groups', rows.length);
})().catch(error => { console.error(error.message); process.exitCode = 1; }).finally(() => p.$disconnect());
