const assert = require('node:assert/strict');
const fs = require('node:fs');
const { execFileSync } = require('node:child_process');
require('@next/env').loadEnvConfig(process.cwd());
const { PrismaClient } = require('@prisma/client');
const p = new PrismaClient();
(async () => {
  const processes = JSON.parse(execFileSync('/usr/local/bin/pm2', ['jlist'], { encoding: 'utf8' }));
  const app = processes.find(p => p.name === 'doran-whatsapp');
  assert(app); const e = app.pm2_env;
  assert.equal(e.status, 'online'); assert.equal(e.max_memory_restart, 6144 * 1024 * 1024);
  assert.equal(e.exp_backoff_restart_delay, 1000); assert.equal(e.kill_timeout, 65000);
  assert.equal(e.log_date_format, 'YYYY-MM-DD HH:mm:ss Z'); assert.equal(e.instances, 1);
  assert.equal(e.exec_mode, 'fork_mode'); assert.equal(e.autorestart, true); assert.equal(e.watch, false);
  assert(e.node_args.includes('--max-old-space-size=4096'));
  assert.equal(e.WHATSAPP_ENABLED, 'true'); assert.equal(e.DISPATCH_QUEUE_ENABLED, 'true');
  assert.equal(e.QUEUE_ENABLED, 'false'); assert.equal(e.DISPATCH_CONCURRENCY, '32');
  const databaseUrl = new URL(e.DATABASE_URL || process.env.DATABASE_URL);
  assert.equal(databaseUrl.searchParams.get('connection_limit'), '40');
  assert.equal(databaseUrl.searchParams.get('pool_timeout'), '10');
  assert.equal((await fetch('http://127.0.0.1:3000/signin')).status, 200);
  assert.equal((await fetch('https://dashboard.jeblast.com/signin')).status, 200);
  const admin = await p.user.findFirst({ where: { email: 'admin@gmail.com', role: 'ADMIN', isActive: true, approvalStatus: 'APPROVED' } });
  assert(admin);
  const r = await fetch('http://127.0.0.1:3000/health/dispatch', { headers: { Authorization: 'Bearer ' + admin.token } });
  const health = await r.json();
  assert(!health.alerts.includes('WORKER_NOT_RUNNING'));
  assert(!health.alerts.includes('POLL_STALE'));
  console.log('LIVE_PM2_SETTINGS_HTTP_AND_WORKER_PASSED', JSON.stringify({ pid: app.pid, memoryMiB: Math.round(app.monit.memory / 1024 / 1024), cpu: app.monit.cpu, healthStatus: r.status, healthy: health.healthy, alerts: health.alerts, metrics: health.metrics }));
})().catch(error => { console.error(error.message); process.exitCode = 1; }).finally(() => p.$disconnect());
